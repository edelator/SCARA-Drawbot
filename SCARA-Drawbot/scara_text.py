# ── Geometry ─────────────────────────────────────────────────────────────────

def apply_transform(x, y, rotation_deg):
    r = math.radians(rotation_deg)
    return round(x*math.cos(r) - y*math.sin(r), 3), \
           round(x*math.sin(r) + y*math.cos(r), 3)

def measure_line(text, height_mm, spacing):
    scale = height_mm / 21.0
    w = 0.0
    for ch in text:
        c = ch if ch in HERSHEY else '?'
        w += (HERSHEY[c][0] + 2) * scale * spacing
    return w

def render_line(text, ox, oy, height_mm, spacing, rotation_deg):
    """Render one line of text. Returns list of GCode strings."""
    scale = height_mm / 21.0
    cmds = []
    cx = ox

    for ch in text:
        c = ch if ch in HERSHEY else '?'
        char_width, strokes = HERSHEY[c]

        if ch == ' ':
            cx += char_width * scale * spacing * 0.7
            continue

        pen_down = False
        for sx, sy in strokes:
            if sx == -999:
                if pen_down:
                    cmds.append("M5")
                    pen_down = False
            else:
                wx = cx + sx * scale
                wy = oy + sy * scale
                tx, ty = apply_transform(wx, wy, rotation_deg)
                if not pen_down:
                    cmds.append(f"G0 X{tx} Y{ty}")
                    cmds.append("M3")
                    pen_down = True
                else:
                    cmds.append(f"G1 X{tx} Y{ty}")

        if pen_down:
            cmds.append("M5")

        cx += (char_width + 2) * scale * spacing

    return cmds

# ── CLI ───────────────────────────────────────────────────────────────────────

def parse_args():
    p = argparse.ArgumentParser(
        description='Generate Hershey font GCode for SCARA robot',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__.split('Usage:')[1] if 'Usage:' in __doc__ else ''
    )
    p.add_argument('text', help='Text to draw. Use | to separate lines.')
    p.add_argument('--height',   default='12',  help='Height in mm. Single value or comma-separated per line (e.g. 8,12,14)')
    p.add_argument('--line-gap', type=float, default=4.0,   help='Gap between lines in mm (default: 4)')
    p.add_argument('--spacing',  type=float, default=1.0,   help='Letter spacing multiplier (default: 1.0)')
    p.add_argument('--x-offset', type=float, default=0.0,   help='X offset from centre mm')
    p.add_argument('--y-offset', type=float, default=0.0,   help='Y offset from centre mm')
    p.add_argument('--rotation', type=float, default=-5.0,  help='Canvas rotation correction degrees (default: -5)')
    p.add_argument('--no-home',  action='store_true',        help='Skip G28/GOHOME')
    p.add_argument('--output',   default=None,               help='Output filename')
    p.add_argument('--send',     default=None,               help='Serial port to send to robot')
    p.add_argument('--preview',  action='store_true',        help='Show layout without writing')
    p.add_argument('--list-chars', action='store_true',      help='List available characters')
    return p.parse_args()

def main():
    args = parse_args()

    if args.list_chars:
        chars = sorted(HERSHEY.keys())
        print("Available characters:")
        for i in range(0, len(chars), 32):
            print(' '.join(chars[i:i+32]))
        return

    # Split text into lines
    text_lines = args.text.split('|')

    # Parse heights
    heights_raw = args.height.split(',')
    if len(heights_raw) == 1:
        heights = [float(heights_raw[0])] * len(text_lines)
    else:
        heights = [float(h) for h in heights_raw]
        while len(heights) < len(text_lines):
            heights.append(heights[-1])

    # Calculate layout
    line_gap = args.line_gap
    total_h = sum(heights) + line_gap * (len(text_lines) - 1)
    widths = [measure_line(t, h, args.spacing) for t,h in zip(text_lines, heights)]

    print(f"Text layout ({len(text_lines)} line{'s' if len(text_lines)>1 else ''}):")
    for i,(text,h,w) in enumerate(zip(text_lines,heights,widths)):
        warn = ' ⚠ wide' if w > 110 else ''
        print(f"  Line {i+1}: \"{text}\" @ {h}mm — {w:.0f}mm wide{warn}")
    print(f"  Total height: {total_h:.0f}mm")
    print(f"  Rotation: {args.rotation}°  Spacing: {args.spacing}x")

    if max(widths) > 130:
        print("  WARNING: Some lines exceed 130mm. Consider --spacing 0.85 or shorter text.")

    if args.preview:
        print("\nPreview mode — no file written.")
        return

    # Generate GCode
    gcode = [
        f"; Hershey Simplex Roman — generated by scara_text.py",
        f"; Text: {args.text.replace('|', ' / ')}",
        f"; Heights: {args.height}mm  Rotation: {args.rotation}°",
    ]

    if not args.no_home:
        gcode += ["G28", "GOHOME"]
    gcode.append("M5")

    y_cursor = total_h / 2 + args.y_offset

    for text, height, width in zip(text_lines, heights, widths):
        x_start = -width / 2 + args.x_offset
        gcode.append(f"\n; \"{text}\" @ {height}mm")
        cmds = render_line(text, x_start, y_cursor - height,
                           height, args.spacing, args.rotation)
        gcode.extend(cmds)
        y_cursor -= height + line_gap

    gcode += ["", "M5", "G0 X0 Y0"]

    # Determine output filename
    if args.output:
        outfile = args.output
    else:
        safe = args.text[:20].replace('|','_').replace(' ','_')
        safe = ''.join(c for c in safe if c.isalnum() or c=='_')
        outfile = f"text_{safe}.gcode"

    with open(outfile, 'w') as f:
        f.write('\n'.join(gcode) + '\n')

    n_moves = sum(1 for l in gcode if l.startswith(('G0','G1')))
    n_pens  = sum(1 for l in gcode if l.strip() in ('M3','M5'))
    print(f"\nWritten '{outfile}' — {n_moves} moves, {n_pens} pen ops")

    if args.send:
        print(f"\nSending to robot on {args.send}...")
        os.system(f"python3 gcode_sender.py {outfile} {args.send}")

if __name__ == '__main__':
    main()
